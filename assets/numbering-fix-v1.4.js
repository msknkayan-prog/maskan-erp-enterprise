/* v1.4 automatic numbering fix: do not stop at absent fields. */
(function(){
  const fields={party_code:'party',project_code:'project',contract_number:'contract',request_number:'request',certificate_number:'certificate',payment_number:'payment',po_number:'purchase_order'};
  let busy=false;
  async function fill(){
    if(busy || !window.sb || typeof companyId!=='function')return;
    const root=document.querySelector('#modalRoot');if(!root)return;
    busy=true;
    try{
      for(const [name,type] of Object.entries(fields)){
        const input=root.querySelector(`input[name="${name}"]`);
        if(!input || input.value || input.dataset.v14Numbered)continue;
        input.dataset.v14Numbered='1';input.placeholder=input.placeholder||'يُنشأ تلقائياً';
        const company=companyId();if(!company)continue;
        const {data,error}=await sb.rpc('next_erp_number',{p_company_id:company,p_doc_type:type});
        if(!error && data && !input.value){input.value=data;input.dataset.autoGenerated='1';input.title='رقم مولد تلقائياً';}
      }
    }finally{busy=false}
  }
  new MutationObserver(()=>fill().catch(()=>{})).observe(document.body,{childList:true,subtree:true});
  window.addEventListener('load',()=>fill().catch(()=>{}));
})();