/* Maskan ERP Enterprise v1.3 — productivity enhancements
   Adds: automatic document numbering, generic Excel export, print/PDF actions,
   clearer permission guidance, and production readiness markers.
   Loaded after the production repair/import patches.
*/
(function(){
  'use strict';

  const RELEASE='Enterprise Final v1.3';
  document.documentElement.dataset.erpRelease='v1.3-enterprise';
  document.title='مسكن الكيان ERP — Enterprise Final v1.3';

  const numberFields={
    party_code:'party',
    project_code:'project',
    contract_number:'contract',
    request_number:'request',
    certificate_number:'certificate',
    payment_number:'payment',
    po_number:'purchase_order'
  };

  async function getNextNumber(docType){
    if(!window.sb || !window.profile || typeof companyId!=='function')return null;
    const cid=companyId();
    if(!cid)return null;
    const {data,error}=await sb.rpc('next_erp_number',{p_company_id:cid,p_doc_type:docType});
    if(error){
      // Keep forms usable even if the optional numbering migration has not been run yet.
      console.warn('Automatic numbering unavailable:',error.message);
      return null;
    }
    return data||null;
  }

  async function fillAutomaticNumbers(root=document){
    for(const [field,docType] of Object.entries(numberFields)){
      const input=root.querySelector(`input[name="${field}"]`);
      if(!input || input.value || input.dataset.autoNumberAttempted)return;
      input.dataset.autoNumberAttempted='1';
      input.placeholder=input.placeholder||'يُنشأ تلقائياً';
      const number=await getNextNumber(docType);
      if(number && !input.value){
        input.value=number;
        input.dataset.autoGenerated='1';
        input.title='رقم مولد تلقائياً ويمكن تعديله قبل الحفظ';
      }
    }
  }

  function tableToExcel(table,filename){
    if(!window.XLSX){
      if(typeof toast==='function')toast('تعذر تحميل أداة Excel. تحقق من الاتصال بالإنترنت',true);
      return;
    }
    const clone=table.cloneNode(true);
    clone.querySelectorAll('button,.row-actions').forEach(x=>x.remove());
    const wb=XLSX.utils.book_new();
    const ws=XLSX.utils.table_to_sheet(clone,{raw:true});
    XLSX.utils.book_append_sheet(wb,ws,'Maskan ERP');
    XLSX.writeFile(wb,filename);
  }

  function addEnterpriseActions(){
    const content=document.querySelector('#content');
    if(!content)return;
    const table=content.querySelector('table');
    const toolbar=content.querySelector('.toolbar');
    if(!table || !toolbar)return;
    let actions=toolbar.querySelector('.actions');
    if(!actions){actions=document.createElement('div');actions.className='actions';toolbar.appendChild(actions)}

    if(!actions.querySelector('.enterprise-excel')){
      const b=document.createElement('button');
      b.type='button';b.className='btn enterprise-excel';b.textContent='تصدير Excel';
      b.onclick=()=>tableToExcel(table,`Maskan_${(window.currentPage||'report')}_${new Date().toISOString().slice(0,10)}.xlsx`);
      actions.appendChild(b);
    }
    if(!actions.querySelector('.enterprise-pdf') && ![...actions.querySelectorAll('button')].some(b=>/طباعة|PDF/i.test(b.textContent||''))){
      const b=document.createElement('button');
      b.type='button';b.className='btn enterprise-pdf';b.textContent='طباعة / PDF';
      b.onclick=()=>window.print();actions.appendChild(b);
    }
  }

  function addProductionBadge(){
    const top=document.querySelector('.topmeta');
    if(!top || top.querySelector('.enterprise-release-badge'))return;
    const badge=document.createElement('span');
    badge.className='pill enterprise-release-badge';
    badge.textContent='v1.3 Production';
    badge.title='Maskan ERP Enterprise production release';
    top.appendChild(badge);
  }

  // Enhance the existing System page without replacing its current diagnostics/backup tools.
  if(typeof window.system==='function' || typeof system==='function'){
    const originalSystem=window.system||system;
    window.system=async function(){
      await originalSystem();
      const content=document.querySelector('#content');
      if(!content)return;
      const extra=document.createElement('div');
      extra.className='card full-span';
      extra.style.marginTop='14px';
      extra.innerHTML=`<div class="toolbar"><h3>أدوات التشغيل المؤسسية</h3><span class="status-pill success">${RELEASE}</span></div>
        <div class="grid three">
          <div><b>الترقيم التلقائي</b><p class="hint">أرقام المشاريع والعقود وطلبات الصرف والمستخلصات والدفعات وأوامر الشراء تُولد من قاعدة البيانات.</p></div>
          <div><b>تصدير Excel</b><p class="hint">تمت إضافة تصدير Excel مباشر للجداول التشغيلية والتقارير.</p></div>
          <div><b>PDF رسمي</b><p class="hint">استخدم «طباعة / PDF» ثم اختر Save as PDF من المتصفح.</p></div>
        </div>`;
      content.appendChild(extra);
    };
  }

  // Add a concise permissions legend to the existing users page.
  if(typeof window.users==='function' || typeof users==='function'){
    const originalUsers=window.users||users;
    window.users=async function(){
      await originalUsers();
      const card=document.querySelector('#content .card');
      if(card && !card.querySelector('.enterprise-role-guide')){
        const guide=document.createElement('div');
        guide.className='enterprise-role-guide hint';
        guide.style.marginTop='12px';
        guide.innerHTML='<b>دليل الصلاحيات:</b> مدير النظام = كامل الصلاحيات، المدير العام = إشراف واعتماد، المدير المالي/المحاسب = المالية، مدير المشروع = المشاريع وطلبات الصرف، المشتريات = الشراء والمخزون، مشاهدة فقط = قراءة دون تعديل.';
        card.appendChild(guide);
      }
    };
  }

  const observer=new MutationObserver(()=>{
    addEnterpriseActions();
    addProductionBadge();
    const modal=document.querySelector('#modalRoot');
    if(modal)fillAutomaticNumbers(modal).catch(()=>{});
  });
  observer.observe(document.body,{subtree:true,childList:true});

  window.addEventListener('load',()=>{
    addProductionBadge();
    addEnterpriseActions();
    const modal=document.querySelector('#modalRoot');
    if(modal)fillAutomaticNumbers(modal).catch(()=>{});
  });
})();
